export type Hardheid = 'zacht' | 'matig' | 'matig hard' | 'hard' | 'zeer hard';

export interface Gemeente {
  naam: string;
  slug: string;
  provincie: string;
  hardheid: number; // °dH (Duitse hardheidsgraden)
  categorie: Hardheid;
  waterbedrijf: string;
}

function categoriseer(dh: number): Hardheid {
  if (dh < 4) return 'zacht';
  if (dh < 8) return 'matig';
  if (dh < 12) return 'matig hard';
  if (dh < 18) return 'hard';
  return 'zeer hard';
}

function g(naam: string, provincie: string, hardheid: number, waterbedrijf: string): Gemeente {
  return {
    naam,
    slug: naam.toLowerCase().replace(/\s+/g, '-').replace(/[^a-z0-9-]/g, ''),
    provincie,
    hardheid,
    categorie: categoriseer(hardheid),
    waterbedrijf,
  };
}

